CREATE TABLE public.review_photos (
    review_id bigint NOT NULL REFERENCES public.reviews (id) ON DELETE CASCADE,
    media_id uuid NOT NULL UNIQUE REFERENCES public.media_assets (id) ON DELETE RESTRICT,
    sort_order smallint NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (review_id, media_id),
    CONSTRAINT ck_review_photos_sort_order CHECK (sort_order >= 0)
);
CREATE INDEX idx_review_photos_review_order ON public.review_photos (review_id, sort_order, media_id);

CREATE TABLE public.review_likes (
    user_id uuid NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
    review_id bigint NOT NULL REFERENCES public.reviews (id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, review_id)
);
CREATE INDEX idx_review_likes_review ON public.review_likes (review_id, user_id);

CREATE TABLE public.menu_wishlists (
    user_id uuid NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
    menu_id bigint NOT NULL REFERENCES public.menus (id) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, menu_id)
);
CREATE INDEX idx_menu_wishlists_menu ON public.menu_wishlists (menu_id, user_id);

CREATE FUNCTION public.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
BEGIN
    NEW.updated_at := pg_catalog.now();
    RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.set_updated_at() FROM PUBLIC, anon, authenticated, service_role;

CREATE TRIGGER trg_profiles_updated_at
    BEFORE UPDATE ON public.profiles
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER trg_restaurants_updated_at
    BEFORE UPDATE ON public.restaurants
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER trg_menus_updated_at
    BEFORE UPDATE ON public.menus
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE FUNCTION public.guard_review_update()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
BEGIN
    IF NEW.user_id IS DISTINCT FROM OLD.user_id
       OR NEW.menu_id IS DISTINCT FROM OLD.menu_id
       OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'review identity fields are immutable';
    END IF;
    NEW.updated_at := pg_catalog.now();
    RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.guard_review_update() FROM PUBLIC, anon, authenticated, service_role;
CREATE TRIGGER trg_reviews_guard_update
    BEFORE UPDATE ON public.reviews
    FOR EACH ROW EXECUTE FUNCTION public.guard_review_update();

CREATE FUNCTION public.handle_new_auth_user_profile()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog
AS $$
DECLARE
    v_display_name text;
BEGIN
    v_display_name := pg_catalog.btrim(NEW.raw_user_meta_data ->> 'display_name');
    IF v_display_name IS NULL OR v_display_name = '' THEN
        v_display_name := '회원';
    END IF;
    IF pg_catalog.char_length(v_display_name) > 80 THEN
        v_display_name := pg_catalog.left(v_display_name, 80);
    END IF;
    INSERT INTO public.profiles (user_id, display_name)
    VALUES (NEW.id, v_display_name)
    ON CONFLICT (user_id) DO NOTHING;
    RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.handle_new_auth_user_profile() FROM PUBLIC, anon, authenticated, service_role;
CREATE TRIGGER trg_auth_user_profile_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_auth_user_profile();

